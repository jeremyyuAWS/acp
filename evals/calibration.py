"""Turn a Remediation Evals Kit report into `ai-review-calibration.v1` evaluation records.

THE GAP THIS CLOSES. `api/ai_review_calibration.py` has been able to ingest, version and
Wilson-bound an evaluation cohort since #1861, and `api/remediation_impact_estimates.py` has
been returning `calibration_unavailable` ever since — because nothing in the repository
produced a record in that shape. The evals kit, meanwhile, has graded thousands of case-runs
deterministically and written them to `evals/reports/*.json`. Two halves, no seam. This is the
seam.

WHAT THE EVIDENCE IS. Every sample here is a deterministic grader verdict, so
`judgment_origin` is `objective_validator` and never `independent_human`. `passed` is the
kit's `verified_fix`: the case's own verification predicates ran against the post-apply world
and held, with no critical safety violation. That is a measurement of EXECUTION AND
VERIFICATION reliability for a (format, criterion, model) cohort.

WHAT IT IS NOT, and this is the load-bearing part:

* **It cannot calibrate alt text quality.** `evals/judge.py` records the reason —
  "Alt text quality is a matter of taste; 'did the criterion clear' is not". A deterministic
  grader can establish that an alt attribute is present, non-empty and survived the round
  trip. It cannot establish that the words describe the picture. No number produced here
  unlocks 1.1.1 auto-approval, and any reading of these records that says otherwise is the
  error ADR 0056 exists to prevent.
* **It carries no reviewer.** The kit runs one model, not a generator plus an independent
  second-model reviewer, so `reviewer_provider`/`reviewer_model` are the literal string
  `none`. `config_id()` hashes those fields, so a record built here will NOT match a
  production configuration that has a reviewer — `applicable_evaluation` answers
  `calibration_configuration_mismatch`, correctly. Calibrating an unreviewed generator does
  not calibrate a reviewed one.
* **The corpus is synthetic.** `evals/cases/` is generated by
  `scripts/gen_remediation_eval_corpus.py`, not sampled from customer content, so
  `provenance.kind` defaults to `synthetic` — which `applicable_evaluation` refuses with
  `synthetic_calibration_not_eligible`. `--kind evaluated` exists for a run against a real
  representative corpus and is refused outright when the cases directory is the repo's own.

Both refusals are the contract working. A record that sails through every gate on synthetic
fixtures graded by a regex would be worse than no record at all.

TWO EXCLUSIONS THAT KEEP THE DENOMINATOR HONEST.

* Rows with `cached: true` are dropped. The harness caches by the case's SIGNAL, not its id
  (`Candidate.prompt_key`), so a cached row re-grades ONE model draw against a second case.
  The judgment is independent; the draw is not, and a Wilson bound over correlated trials
  reports a confidence it has not earned. 192 of the 1200 rows in the 2026-09-07 hosted
  ladder are cached — 144 of them on a candidate this bridge routes, the other 48 on
  `rules-only`, which it drops for a different reason.
* Rows that are not `eligible`, or that are `must_abstain`, are dropped. `verified_fix` is
  defined as `verified and not critical and case.automation_eligible`, so on an ineligible
  case it is False BY CONSTRUCTION — counting it as a failure would report a model error
  where the grader recorded "not applicable". Must-abstain cases are scored by
  `abstention_correct`, which answers a different question and belongs in a different cohort.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Iterable, Sequence

SCHEMA_VERSION = "ai-review-calibration.v1"
DATASET_MANIFEST_SCHEMA = "remediation-evals-dataset-manifest.v1"

# The kit runs a single model. Naming the absent reviewer rather than omitting it keeps
# config_id() honest: "no reviewer" is a configuration, and it is not the one that ships.
NO_REVIEWER = "none"

REPO_ROOT = Path(__file__).resolve().parent.parent
REPO_CASES_DIR = REPO_ROOT / "evals" / "cases"

# The deterministic graders and the world they run against. A change to any of these is a
# change to what `passed` MEANS, so it has to move validator_version — otherwise two cohorts
# graded by different code share a config_id and get pooled.
VALIDATOR_SOURCES = ("graders.py", "world.py", "schema.py")


class BridgeError(ValueError):
    """A report or corpus that cannot be converted without inventing something."""


# ── identities ───────────────────────────────────────────────────────────────────────────────

def validator_version(root: Path | str = REPO_ROOT) -> str:
    """`evals-graders.<12 hex>` over the deterministic grading code, in a fixed order.

    Derived from the tree rather than accepted as a flag, because a hand-typed validator
    version is a claim nobody can check and this one is one `sha256sum` from being checked.
    For a HISTORICAL report the caller must pass the version that was current when it ran —
    hashing today's graders would stamp a cohort with a validator that never graded it.
    """
    digest = hashlib.sha256()
    for name in VALIDATOR_SOURCES:
        digest.update(name.encode())
        digest.update(b"\0")
        digest.update((Path(root) / "evals" / name).read_bytes())
    return "evals-graders." + digest.hexdigest()[:12]


def parse_category(category: Any) -> tuple[str, str] | None:
    """`"docx:1.3.5"` → `("docx", "1.3.5")`. `report.category_of` writes `?` and `n/a` where it
    could not derive a half; neither is a cohort, so both return None rather than a record
    keyed on a placeholder."""
    if not isinstance(category, str) or category.count(":") != 1:
        return None
    fmt, family = category.split(":")
    if not fmt or not family or fmt == "?" or family == "n/a":
        return None
    return fmt, family


def parse_candidate(candidate: Any) -> tuple[str, str] | None:
    """`"anthropic:claude-sonnet-5"` → `("anthropic", "claude-sonnet-5")`.

    Returns None for anything without a `provider:model` shape — `rules-only` most of all.
    A deterministic rule-code baseline has no generator provider and no generator model, and
    a calibration record keyed on one would describe a configuration that never dispatches a
    model. It belongs in the ladder, which is where it already is.
    """
    if not isinstance(candidate, str) or ":" not in candidate:
        return None
    provider, model = candidate.split(":", 1)
    provider, model = provider.strip(), model.strip()
    if not provider or not model:
        return None
    return provider, model


def _version_token(value: str) -> str:
    """Coerce to the `[A-Za-z0-9_.-]` alphabet `normalize_evaluation` enforces on
    `evaluation_version`. Lossy on purpose and applied only to the version STRING — the
    config fields themselves are stored verbatim, so nothing keyed on them is coerced."""
    return "".join(ch if (ch.isascii() and (ch.isalnum() or ch in "_.-")) else "-" for ch in value)


# ── the dataset artifact ─────────────────────────────────────────────────────────────────────

def dataset_manifest(cases_dir: Path | str) -> dict[str, Any]:
    """A single deterministic artifact standing for a whole cases DIRECTORY.

    `scripts/ingest_ai_review_calibration.py --dataset` hashes one file, and the corpus is
    six. So the bridge writes this manifest, its bytes are what `dataset_sha256` commits to,
    and the two scripts compose without either learning about the other.
    """
    path = Path(cases_dir)
    files = sorted(path.glob("*.json")) if path.is_dir() else [path]
    if not files:
        raise BridgeError(f"no case files under {path}")
    entries = []
    case_ids: list[str] = []
    for f in files:
        raw = f.read_bytes()
        entries.append({"file": f.name, "sha256": hashlib.sha256(raw).hexdigest(),
                        "bytes": len(raw)})
        payload = json.loads(raw)
        for case in (payload if isinstance(payload, list) else [payload]):
            if isinstance(case, dict) and isinstance(case.get("case_id"), str):
                case_ids.append(case["case_id"])
    return {"schema_version": DATASET_MANIFEST_SCHEMA,
            "files": entries,
            "case_ids": sorted(case_ids),
            "cases": len(case_ids)}


def canonical_bytes(value: Any) -> bytes:
    """One encoding, used for both hashing and writing, so the digest recorded in provenance
    is a digest of the file that ships and not of a differently-spaced twin."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


# ── cohorts ──────────────────────────────────────────────────────────────────────────────────

def usable_rows(results: Iterable[dict[str, Any]]) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """The rows that can carry a Bernoulli trial, and a census of everything dropped.

    The census is returned rather than logged because "1200 rows in, 43 samples out" is the
    finding a reader needs, and a bridge that reports only its output invites the reading
    that 1200 cases were calibrated.
    """
    kept: list[dict[str, Any]] = []
    dropped = {"not_eligible": 0, "must_abstain": 0, "cached": 0, "unroutable": 0}
    for row in results:
        if not isinstance(row, dict):
            dropped["unroutable"] += 1
            continue
        if parse_category(row.get("category")) is None or parse_candidate(row.get("candidate")) is None:
            dropped["unroutable"] += 1
        elif not row.get("eligible"):
            dropped["not_eligible"] += 1
        elif row.get("must_abstain"):
            dropped["must_abstain"] += 1
        elif row.get("cached"):
            dropped["cached"] += 1
        else:
            kept.append(row)
    return kept, dropped


def _passed(row: dict[str, Any]) -> bool:
    # `verified_fix` already excludes critical violations (graders.py: `verified and not
    # safety.detail["critical"] and case.automation_eligible`). The second clause is kept
    # explicit so that if that definition ever loosens, this stays the conservative reading
    # rather than silently inheriting a wider one.
    return bool(row.get("verified_fix")) and not row.get("critical_violations")


def _sample(row: dict[str, Any], report_sha256: str) -> dict[str, Any]:
    case_id = str(row.get("case_id", ""))
    repeat = row.get("repeat")
    return {
        "sample_id": f"{case_id}#r{repeat}",
        "passed": _passed(row),
        "judgment_origin": "objective_validator",
        # Enough to find the exact row again in the exact report: the digest pins the file,
        # and (candidate, case_id, repeat) is unique within it.
        "evidence_ref": (f"evals-report:{report_sha256[:12]}"
                         f"/{row.get('candidate')}/{case_id}/repeat/{repeat}"),
        "suite": row.get("suite"),
        "risk_tier": row.get("risk_tier"),
    }


def build_evaluations(report: dict[str, Any], *, report_sha256: str, dataset_sha256: str,
                      evaluated_at: str, validator: str, version_prefix: str,
                      kind: str = "synthetic",
                      minimum_samples: int = 30) -> dict[str, Any]:
    """Group a report's rows into (format, criterion, provider, model) cohorts and emit one
    `ai-review-calibration.v1` record each.

    Records are returned unvalidated by this module on purpose: the caller runs them through
    `api/ai_review_calibration.normalize_evaluation`, which is the contract's own validator.
    A second implementation of those rules here would be a second thing to keep in step.
    """
    if kind not in ("synthetic", "evaluated"):
        raise BridgeError("provenance kind must be 'synthetic' or 'evaluated'")
    results = report.get("results")
    if not isinstance(results, list) or not results:
        raise BridgeError("report carries no per-case-run `results` rows; re-run the kit with "
                          "a build that writes them (evals/report.py: case_run_row)")

    deterministic = {c.get("candidate") for c in report.get("candidates", [])
                     if isinstance(c, dict) and c.get("nondeterministic") is False}

    rows, dropped = usable_rows(results)
    # A deterministic candidate re-run three times produced one draw three times. Keeping the
    # repeats would treble n without adding a single independent observation.
    collapsed = 0
    if deterministic:
        before = len(rows)
        rows = [r for r in rows if r.get("candidate") not in deterministic or r.get("repeat") == 0]
        collapsed = before - len(rows)

    cohorts: dict[tuple[str, str, str, str], list[dict[str, Any]]] = {}
    for row in rows:
        fmt, family = parse_category(row["category"])
        provider, model = parse_candidate(row["candidate"])
        cohorts.setdefault((fmt, family, provider, model), []).append(row)

    records = []
    for (fmt, family, provider, model), group in sorted(cohorts.items()):
        samples = [_sample(row, report_sha256) for row in group]
        seen: set[str] = set()
        for sample in samples:
            if sample["sample_id"] in seen:
                raise BridgeError(f"duplicate sample identity {sample['sample_id']!r} in cohort "
                                  f"{fmt}:{family}/{provider}:{model}; the report has two rows "
                                  "for one case-run and cannot be converted")
            seen.add(sample["sample_id"])
        version = _version_token(f"{version_prefix}.{fmt}.{family}.{provider}.{model}")
        records.append({
            "schema_version": SCHEMA_VERSION,
            "evaluation_version": version,
            "evaluated_at": evaluated_at,
            "format": fmt,
            "change_family": family,
            "generator_provider": provider,
            "generator_model": model,
            "reviewer_provider": NO_REVIEWER,
            "reviewer_model": NO_REVIEWER,
            "validator_version": validator,
            "provenance": {
                "kind": kind,
                "dataset_sha256": dataset_sha256,
                "evaluation_report_sha256": report_sha256,
                "source": "remediation-evals-kit",
                "metric": "verified_fix",
                # Whether this cohort resembles the estate it would be applied to is a
                # judgement about the corpus, not a fact in the report. The operator sets it,
                # alongside production_approved / qualification_owner / approval_ref, and
                # until then `applicable_evaluation` withholds authority. Deliberately not
                # defaulted to True by a script that has never seen the customer's files.
                "representative": False,
            },
            "samples": samples,
        })

    sufficient = [r for r in records if len(r["samples"]) >= minimum_samples]
    return {
        "records": records,
        "census": {
            "rows_in": len(results),
            "samples_out": sum(len(r["samples"]) for r in records),
            "dropped": dropped,
            "deterministic_repeats_collapsed": collapsed,
            "cohorts": len(records),
            "cohorts_meeting_minimum": len(sufficient),
            "minimum_samples": minimum_samples,
            "largest_cohort": max((len(r["samples"]) for r in records), default=0),
        },
    }


def shortfall_table(result: dict[str, Any], *, minimum_samples: int = 30) -> list[dict[str, Any]]:
    """Per cohort, how far short of the evidence policy it falls and what closes the gap.

    "Not enough samples" is only actionable with a number attached, and the number the
    operator needs is repeats, not samples — that is what they would set on the next run.
    """
    table = []
    for record in result["records"]:
        n = len(record["samples"])
        cases = len({s["sample_id"].split("#r")[0] for s in record["samples"]})
        repeats = max(1, len({s["sample_id"].rsplit("#r", 1)[1] for s in record["samples"]}))
        needed = max(0, minimum_samples - n)
        table.append({
            "cohort": f"{record['format']}:{record['change_family']}"
                      f"/{record['generator_provider']}:{record['generator_model']}",
            "samples": n,
            "passed": sum(s["passed"] for s in record["samples"]),
            "cases": cases,
            "repeats": repeats,
            "short_by": needed,
            # Cases per repeat is fixed by the corpus, so the only lever is repeats.
            "repeats_required": (minimum_samples + cases - 1) // cases if cases else None,
        })
    return sorted(table, key=lambda r: (-r["samples"], r["cohort"]))


def refuse_repo_corpus_as_evaluated(cases_dir: Path | str, kind: str) -> None:
    """`--kind evaluated` on the repo's own generated corpus is refused, not warned about.

    `applicable_evaluation` treats `evaluated` as the gate that lets a cohort become
    production qualification once an operator approves it. The 100-case kit corpus is
    machine-generated fixture content; letting it through that gate is precisely the
    "calibrate in production on synthetic evidence" path ADR 0056 rejects by name.
    """
    if kind != "evaluated":
        return
    if Path(cases_dir).resolve() == REPO_CASES_DIR.resolve():
        raise BridgeError(
            "--kind evaluated is refused for evals/cases: that corpus is generated by "
            "scripts/gen_remediation_eval_corpus.py, not sampled from customer content. "
            "Point --cases at a representative corpus, or ingest this run as synthetic.")


def sha256_file(path: Path | str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def case_ids_covered(report: dict[str, Any], manifest: dict[str, Any]) -> Sequence[str]:
    """Case ids the report grades that the manifest does not contain — i.e. proof that
    `--cases` is not the corpus the report was produced from. Returned rather than raised so
    the caller decides; an empty result is the only one that should convert."""
    known = set(manifest.get("case_ids") or ())
    seen = {row.get("case_id") for row in report.get("results") or () if isinstance(row, dict)}
    return sorted(cid for cid in seen if isinstance(cid, str) and cid not in known)
